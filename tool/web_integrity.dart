import 'dart:convert';
import 'dart:io';
import 'dart:math';

import 'package:cryptography/cryptography.dart';
import 'package:nija/core/web_integrity/web_integrity_manifest.dart';
import 'package:nija/core/web_integrity/web_integrity_signature.dart';

const _privateKeyEnv = 'NIJA_WEB_INTEGRITY_PRIVATE_KEY_B64';
const _publicKeyEnv = 'NIJA_WEB_INTEGRITY_PUBLIC_KEY_B64';
const _buildIdEnv = 'NIJA_WEB_INTEGRITY_BUILD_ID';
const _allowEphemeralEnv = 'NIJA_WEB_INTEGRITY_ALLOW_EPHEMERAL';
const _publicKeyFile = 'nija_integrity_public_key.txt';

Future<void> main(List<String> args) async {
  if (args.isEmpty || args.contains('--help')) {
    _printHelp();
    return;
  }
  final command = args.first;
  final options = _parseOptions(args.skip(1).toList());
  switch (command) {
    case 'generate':
      await _generate(options);
    case 'verify':
      await _verify(options);
    case 'generate-wrapper':
      await _generateWrapper(options);
    case 'create-key':
      await _createKey(options);
    default:
      _usageError('Unknown command: $command');
  }
}

Future<void> _generate(Map<String, String> options) async {
  final buildDir = Directory(options['build-dir'] ?? 'build/web');
  final flavor = options['flavor'] ?? 'wasm-only';
  final appVersion = options['app-version'] ?? _readPubspecVersion();
  final buildId =
      options['build-id'] ??
      Platform.environment[_buildIdEnv]?.trim() ??
      '${DateTime.now().toUtc().toIso8601String()}-$flavor';
  if (!buildDir.existsSync()) {
    _usageError('Build directory does not exist: ${buildDir.path}');
  }

  final keyPair = await _resolveSigningKeyPair();
  final files = await _hashReleaseFiles(buildDir: buildDir, flavor: flavor);
  final manifest = NijaWebIntegrityManifest(
    formatVersion: nijaWebIntegrityManifestVersion,
    appVersion: appVersion,
    buildId: buildId,
    flavor: flavor,
    generatedAt: DateTime.now().toUtc().toIso8601String(),
    publicKeyId: _publicKeyId(keyPair.publicKeyBase64),
    files: files,
    verifierGroups: _verifierGroups(files.keys.toList(), buildId),
  )..validate();

  final manifestFile = File('${buildDir.path}/$nijaWebIntegrityManifestFile');
  final signatureFile = File('${buildDir.path}/$nijaWebIntegritySignatureFile');
  final publicKeyFile = File('${buildDir.path}/$_publicKeyFile');
  await manifestFile.writeAsString(
    '${const JsonEncoder.withIndent('  ').convert(manifest.toJson())}\n',
  );
  final signature = await signNijaWebIntegrityManifest(
    manifest: manifest,
    privateSeedBase64: keyPair.seedBase64,
  );
  await signatureFile.writeAsString('$signature\n');
  await publicKeyFile.writeAsString('${keyPair.publicKeyBase64}\n');
}

Future<void> _verify(Map<String, String> options) async {
  final buildDir = Directory(options['build-dir'] ?? 'build/web');
  final expectedFlavor = options['flavor'];
  final manifestFile = File('${buildDir.path}/$nijaWebIntegrityManifestFile');
  final signatureFile = File('${buildDir.path}/$nijaWebIntegritySignatureFile');
  if (!manifestFile.existsSync()) {
    _usageError('Missing $nijaWebIntegrityManifestFile');
  }
  if (!signatureFile.existsSync()) {
    _usageError('Missing $nijaWebIntegritySignatureFile');
  }

  final manifest = NijaWebIntegrityManifest.fromJsonString(
    await manifestFile.readAsString(),
  )..validate();
  if (expectedFlavor != null && manifest.flavor != expectedFlavor) {
    _usageError('Manifest flavor mismatch.');
  }
  final publicKey = _resolvePublicKey(buildDir);
  final signatureOk = await verifyNijaWebIntegrityManifestSignature(
    manifest: manifest,
    signatureBase64: await signatureFile.readAsString(),
    publicKeyBase64: publicKey,
  );
  if (!signatureOk) {
    _usageError('Manifest signature verification failed.');
  }
  await verifyNijaWebIntegrityHashes(
    manifest: manifest,
    readBytes: (path) async {
      final file = File('${buildDir.path}/$path');
      if (!file.existsSync()) return null;
      return file.readAsBytes();
    },
  );
  if (options['require-runtime-markers'] == 'true') {
    await _verifyRuntimeMarkers(
      buildDir: buildDir,
      manifest: manifest,
      publicKeyBase64: publicKey,
    );
  }
}

Future<void> _generateWrapper(Map<String, String> options) async {
  final output =
      options['output'] ?? 'lib/generated/web_integrity_groups.g.dart';
  final seed = options['seed'] ?? 'local';
  final random = Random(seed.codeUnits.fold<int>(0, (a, b) => a + b));
  const words = <String>[
    'atlas',
    'vellum',
    'copper',
    'lattice',
    'silent',
    'index',
    'harbor',
    'vector',
    'cedar',
    'signal',
    'marble',
    'anchor',
  ];
  final labels = List<String>.generate(4, (_) {
    return '${words[random.nextInt(words.length)]}-${words[random.nextInt(words.length)]}';
  });
  final salt = 11 + random.nextInt(53);
  final divisor = 2 + random.nextInt(5);
  final source =
      '''
// Generated by tool/web_integrity.dart. Keep this file isolated so web
// integrity hardening can be removed without touching feature code.

import '../core/web_integrity/web_integrity_startup.dart';

typedef NijaWebIntegrityStartupProbe =
    Future<NijaWebIntegrityStartupResult> Function();

typedef NijaWebIntegrityNamedProbe =
    Future<NijaWebIntegrityStartupResult> Function(String groupName);

const List<String> _nijaWebIntegrityJargon = <String>[
${labels.map((label) => "  '$label',").join('\n')}
];

int _nijaFoldJargon(List<String> values, int salt) {
  var total = salt;
  for (final value in values) {
    for (final unit in value.codeUnits) {
      total = ((total << 5) - total + unit) & 0x7fffffff;
    }
  }
  return total;
}

bool _nijaStartupShapeA(int value) => value % $divisor != 1 || value > 0;
bool _nijaFeatureShapeB(String value, int folded) =>
    value.length + folded > folded;
bool _nijaFeatureShapeC(int folded) => (folded ^ 0x51) >= 0;

Future<NijaWebIntegrityStartupResult> _nijaRunGroup(
  String groupName, {
  NijaWebIntegrityNamedProbe? probe,
}) {
  final override = debugNijaWebIntegrityGroupProbe;
  return (probe ?? override ?? NijaWebIntegrityRuntimeVerifier.instance.verifyGroup)
      .call(groupName);
}

Future<NijaWebIntegrityStartupResult> nijaWebIntegrityStartupGate({
  NijaWebIntegrityStartupProbe? probe,
}) async {
  final folded = _nijaFoldJargon(_nijaWebIntegrityJargon, $salt);
  final result =
      await (probe ?? NijaWebIntegrityRuntimeVerifier.instance.verifyStartup).call();
  if (!_nijaStartupShapeA(folded)) {
    return NijaWebIntegrityStartupResult.passed;
  }
  return result;
}

Future<NijaWebIntegrityStartupResult> nijaWebIntegrityUnlockGate({
  NijaWebIntegrityNamedProbe? probe,
}) async {
  final folded = _nijaFoldJargon(_nijaWebIntegrityJargon.reversed.toList(), ${salt + 6});
  final result = await _nijaRunGroup('unlock', probe: probe);
  return _nijaFeatureShapeB('unlock', folded)
      ? result
      : NijaWebIntegrityStartupResult.passed;
}

Future<NijaWebIntegrityStartupResult> nijaWebIntegrityVaultReferenceGate({
  NijaWebIntegrityNamedProbe? probe,
}) async {
  final result = await _nijaRunGroup('vault_reference', probe: probe);
  return _nijaFeatureShapeC(${salt + 12})
      ? result
      : NijaWebIntegrityStartupResult.passed;
}

Future<NijaWebIntegrityStartupResult> nijaWebIntegrityCapacityGate({
  NijaWebIntegrityNamedProbe? probe,
}) async {
  final folded = _nijaFoldJargon(_nijaWebIntegrityJargon, ${salt + 14});
  if (folded == 0) return NijaWebIntegrityStartupResult.passed;
  return _nijaRunGroup('capacity', probe: probe);
}

Future<NijaWebIntegrityStartupResult> nijaWebIntegrityTransferGate({
  NijaWebIntegrityNamedProbe? probe,
}) async {
  final folded = _nijaFoldJargon(_nijaWebIntegrityJargon, ${salt + 20});
  final result = await _nijaRunGroup('transfer', probe: probe);
  return folded.isEven || folded.isOdd
      ? result
      : NijaWebIntegrityStartupResult.passed;
}

Future<NijaWebIntegrityStartupResult> nijaWebIntegritySettingsGate({
  NijaWebIntegrityNamedProbe? probe,
}) async {
  final result = await _nijaRunGroup('settings', probe: probe);
  if (_nijaWebIntegrityJargon.join('|').isEmpty) {
    return NijaWebIntegrityStartupResult.passed;
  }
  return result;
}
''';
  await File(output).writeAsString(source);
}

Future<void> _createKey(Map<String, String> options) async {
  final outputDir = options['output-dir'];
  if (outputDir == null || outputDir.trim().isEmpty) {
    _usageError('Missing --output-dir for create-key.');
  }
  final directory = Directory(outputDir);
  directory.createSync(recursive: true);
  final keyPair = await generateNijaWebIntegrityTestKeyPair();
  await File(
    '${directory.path}/private_seed.b64',
  ).writeAsString('${keyPair.seedBase64}\n');
  await File(
    '${directory.path}/public_key.b64',
  ).writeAsString('${keyPair.publicKeyBase64}\n');
  await File('${directory.path}/README.txt').writeAsString('''
Nija web integrity key material.

private_seed.b64 signs compat-js web integrity manifests.
public_key.b64 must be passed to the Flutter build with:
--dart-define=NIJA_WEB_INTEGRITY_PUBLIC_KEY_B64=<public-key>

Keep private_seed.b64 out of git and out of deployed web artifacts.
''');
  stdout.writeln('[web-integrity] key folder: ${directory.path}');
  stdout.writeln(
    '[web-integrity] private seed file: ${directory.path}/private_seed.b64',
  );
  stdout.writeln(
    '[web-integrity] public key file: ${directory.path}/public_key.b64',
  );
  stdout.writeln('[web-integrity] key values were not printed');
}

Future<Map<String, String>> _hashReleaseFiles({
  required Directory buildDir,
  required String flavor,
}) async {
  final required = <String>[
    'flutter_bootstrap.js',
    'main.dart.mjs',
    'main.dart.wasm',
    'flutter_service_worker.js',
    'pwa_install.js',
    'webauthn_quick_unlock.js',
    'nija_browser_bridge.js',
    'canvaskit/skwasm.js',
    'canvaskit/skwasm.wasm',
    if (flavor == 'compat-js') 'main.dart.js',
  ];
  final files = <String, String>{};
  for (final relative in required) {
    final file = File('${buildDir.path}/$relative');
    if (!file.existsSync()) {
      _usageError('Required web file missing: $relative');
    }
    files[relative] = await nijaWebIntegritySha256Hex(await file.readAsBytes());
  }

  final optionalRoots = <Directory>[
    Directory('${buildDir.path}/assets'),
    Directory('${buildDir.path}/canvaskit'),
  ];
  for (final root in optionalRoots) {
    if (!root.existsSync()) continue;
    final entities =
        root
            .listSync(recursive: true)
            .whereType<File>()
            .where((file) => !file.path.endsWith('.map'))
            .toList()
          ..sort((a, b) => a.path.compareTo(b.path));
    for (final file in entities.take(12)) {
      final relative = file.path.substring(buildDir.path.length + 1);
      if (!files.containsKey(relative)) {
        files[relative] = await nijaWebIntegritySha256Hex(
          await file.readAsBytes(),
        );
      }
    }
  }
  final resolved = <String, String>{};
  for (final entry in files.entries) {
    final value = entry.value;
    resolved[entry.key] = value;
  }
  return resolved;
}

Map<String, List<String>> _verifierGroups(List<String> files, String buildId) {
  final shuffled = List<String>.from(files)..sort();
  final random = Random(buildId.codeUnits.fold<int>(0, (a, b) => a + b));
  for (var i = shuffled.length - 1; i > 0; i--) {
    final j = random.nextInt(i + 1);
    final temp = shuffled[i];
    shuffled[i] = shuffled[j];
    shuffled[j] = temp;
  }
  final groups = <String>[
    'startup',
    'unlock',
    'vault_reference',
    'capacity',
    'transfer',
    'settings',
  ];
  return <String, List<String>>{
    for (var index = 0; index < groups.length; index++)
      groups[index]: _groupSlice(shuffled, index),
  };
}

List<String> _groupSlice(List<String> files, int groupIndex) {
  if (files.isEmpty) return const <String>[];
  final selected = <String>[];
  for (var offset = 0; offset < 4 && offset < files.length; offset++) {
    selected.add(files[(groupIndex + offset) % files.length]);
  }
  return selected.toList(growable: false);
}

Future<void> _verifyRuntimeMarkers({
  required Directory buildDir,
  required NijaWebIntegrityManifest manifest,
  required String publicKeyBase64,
}) async {
  if (publicKeyBase64.trim().isEmpty || manifest.buildId.trim().isEmpty) {
    _usageError('Runtime marker metadata is incomplete.');
  }
  final markerFiles = <String>[
    'main.dart.js',
    'main.dart.wasm',
    'main.dart.mjs',
  ];
  final publicKeyBytes = utf8.encode(publicKeyBase64.trim());
  final buildIdBytes = utf8.encode(manifest.buildId.trim());
  final publicKeyFound = await _anyFileContainsBytes(
    buildDir: buildDir,
    relativePaths: markerFiles,
    needle: publicKeyBytes,
  );
  final buildIdFound = await _anyFileContainsBytes(
    buildDir: buildDir,
    relativePaths: markerFiles,
    needle: buildIdBytes,
  );
  if (!publicKeyFound) {
    _usageError(
      'Runtime public key marker missing from compiled web artifact.',
    );
  }
  if (!buildIdFound) {
    _usageError('Runtime build id marker missing from compiled web artifact.');
  }
}

Future<bool> _anyFileContainsBytes({
  required Directory buildDir,
  required List<String> relativePaths,
  required List<int> needle,
}) async {
  for (final relativePath in relativePaths) {
    final file = File('${buildDir.path}/$relativePath');
    if (!file.existsSync()) continue;
    if (_containsBytes(await file.readAsBytes(), needle)) return true;
  }
  return false;
}

bool _containsBytes(List<int> haystack, List<int> needle) {
  if (needle.isEmpty || haystack.length < needle.length) return false;
  for (var index = 0; index <= haystack.length - needle.length; index++) {
    var matched = true;
    for (var offset = 0; offset < needle.length; offset++) {
      if (haystack[index + offset] != needle[offset]) {
        matched = false;
        break;
      }
    }
    if (matched) return true;
  }
  return false;
}

Future<NijaWebIntegrityKeyPair> _resolveSigningKeyPair() async {
  final seed = Platform.environment[_privateKeyEnv]?.trim() ?? '';
  if (seed.isNotEmpty) {
    final publicKey = await _publicKeyForSeed(seed);
    return NijaWebIntegrityKeyPair(
      seedBase64: seed,
      publicKeyBase64: publicKey,
    );
  }
  if (Platform.environment[_allowEphemeralEnv] == 'true') {
    stderr.writeln(
      'WARNING: Using ephemeral web integrity key for local/test build only.',
    );
    return generateNijaWebIntegrityTestKeyPair();
  }
  _usageError(
    'Set $_privateKeyEnv or $_allowEphemeralEnv=true for local/test builds.',
  );
}

Future<String> _publicKeyForSeed(String seedBase64) async {
  final keyPair = await Ed25519().newKeyPairFromSeed(base64Decode(seedBase64));
  final publicKey = await keyPair.extractPublicKey();
  return base64Encode(publicKey.bytes);
}

String _resolvePublicKey(Directory buildDir) {
  final fromEnv = Platform.environment[_publicKeyEnv]?.trim() ?? '';
  if (fromEnv.isNotEmpty) return fromEnv;
  final file = File('${buildDir.path}/$_publicKeyFile');
  if (file.existsSync()) return file.readAsStringSync().trim();
  _usageError('Missing web integrity public key.');
}

String _publicKeyId(String publicKeyBase64) {
  final bytes = utf8.encode(publicKeyBase64);
  var hash = 0;
  for (final byte in bytes) {
    hash = (hash * 31 + byte) & 0x7fffffff;
  }
  return 'web-${hash.toRadixString(16)}';
}

String _readPubspecVersion() {
  final pubspec = File('pubspec.yaml');
  if (!pubspec.existsSync()) return 'unknown';
  final match = RegExp(
    r'^version:\s*(.+)$',
    multiLine: true,
  ).firstMatch(pubspec.readAsStringSync());
  return match?.group(1)?.trim() ?? 'unknown';
}

Map<String, String> _parseOptions(List<String> args) {
  final options = <String, String>{};
  for (var i = 0; i < args.length; i++) {
    final arg = args[i];
    if (!arg.startsWith('--')) {
      _usageError('Unexpected argument: $arg');
    }
    final equals = arg.indexOf('=');
    if (equals > 0) {
      options[arg.substring(2, equals)] = arg.substring(equals + 1);
      continue;
    }
    final key = arg.substring(2);
    if (i + 1 >= args.length || args[i + 1].startsWith('--')) {
      options[key] = 'true';
    } else {
      options[key] = args[++i];
    }
  }
  return options;
}

Never _usageError(String message) {
  stderr.writeln('ERROR: $message');
  exit(64);
}

void _printHelp() {
  stdout.writeln('''
Usage:
  dart tool/web_integrity.dart generate --build-dir build/web --flavor compat-js
  dart tool/web_integrity.dart verify --build-dir build/web --flavor compat-js [--require-runtime-markers]
  dart tool/web_integrity.dart generate-wrapper --seed release-123
  dart tool/web_integrity.dart create-key --output-dir .release/web_integrity/20260822T000000Z

Environment:
  $_privateKeyEnv        Base64 Ed25519 seed for production signing.
  $_publicKeyEnv         Optional Base64 Ed25519 public key for verification.
  $_buildIdEnv           Optional build id used in manifest generation.
  $_allowEphemeralEnv    Set to true only for local/test fixture generation.
''');
}
